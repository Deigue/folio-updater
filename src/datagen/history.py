"""Refreshing the demo's price history from Yahoo Finance.

The history lives in `datagen.history_data`, which keeps demo generation offline
and deterministic. Refetch it with:

    uv run python -m datagen.history --refresh
"""

from __future__ import annotations

import argparse
from datetime import date, timedelta
from pathlib import Path

import pandas as pd

from datagen.demo import (
    END,
    FIRST_DAY,
    START,
    SYMBOLS,
    USD_LINES,
    USDCAD,
    DemoScenarioError,
    month_index,
)
from datagen.history_data import FIRST_MONTH
from services.symbols import SymbolResolver

_DATA = Path(__file__).with_name("history_data.py")
_DOCSTRING = (
    '"""Month-end closes, dividends and splits for every symbol the demo trades.\n'
    "\n"
    "Generated by `uv run python -m datagen.history --refresh`: do not edit by hand.\n"
    '"""\n'
)
_LINE_LIMIT = 88


def _number(value: float, places: int) -> str:
    """Render a float compactly, without trailing zeros."""
    text = f"{value:.{places}f}".rstrip("0").rstrip(".")
    return text or "0"


def _wrapped(name: str, tokens: list[str]) -> list[str]:  # pragma: no cover
    """Render one price history entry as ruff-stable, line-limited source."""
    one_line = f'    "{name}": "{" ".join(tokens)}",'
    if len(one_line) <= _LINE_LIMIT:
        return [one_line]
    lines = [f'    "{name}": (']
    room = _LINE_LIMIT - len('        ""')
    current = ""
    for token in tokens:
        candidate = f"{current} {token}" if current else token
        if len(candidate) + 1 > room:
            lines.append(f'        "{current} "')
            current = token
        else:
            current = candidate
    lines.append(f'        "{current}"')
    lines.append("    ),")
    return lines


def _render_mapping(  # pragma: no cover
    name: str,
    entries: dict[str, list[str]],
) -> list[str]:
    """Render a `name: dict[str, str] = {...}` price history table."""
    lines = [f"{name}: dict[str, str] = {{"]
    for symbol, tokens in entries.items():
        lines.extend(_wrapped(symbol, tokens))
    lines.append("}")
    return lines


def _window_events(
    series: pd.Series,
    places: int,
    *,
    until: date = END,
) -> list[str]:
    """Render dated events from the demo window's start as `YYYY-MM-DD:value`.

    Args:
        series: Event values by date, as Yahoo serves them.
        places: Decimal places to keep.
        until: The last day to keep. A split may fall after the window and still
            be baked into every stored close, so splits are read without a limit.

    Returns:
        One token per non-zero event from `START` through `until`.
    """
    tokens: list[str] = []
    for day, value in zip(pd.DatetimeIndex(series.index).date, series, strict=True):
        if START <= day <= until and value:
            tokens.append(f"{day.isoformat()}:{_number(float(value), places)}")
    return tokens


def refresh_price_history() -> None:  # pragma: no cover
    """Fetch the price history from Yahoo Finance and rewrite `history_data.py`.

    Raises:
        DemoScenarioError: If Yahoo does not return a full month of closes for
            every symbol.
    """
    import yfinance as yf  # noqa: PLC0415 - a developer tool, heavy, network only

    months = month_index(END) + 1
    resolver = SymbolResolver([], {})
    closes: dict[str, list[str]] = {}
    dividend_events: dict[str, list[str]] = {}
    split_events: dict[str, list[str]] = {}

    derived: list[str] = []
    for symbol in (*SYMBOLS, USDCAD):
        ysymbol = "CAD=X" if symbol == USDCAD else resolver.yahoo_symbol(symbol)
        ticker = yf.Ticker(ysymbol)
        history = ticker.history(
            start=FIRST_DAY.isoformat(),
            end=(END + timedelta(days=1)).isoformat(),
            interval="1mo",
            auto_adjust=False,
        )
        if len(history) != months:
            if symbol in USD_LINES:
                derived.append(symbol)
                continue
            msg = f"{ysymbol}: expected {months} monthly closes, got {len(history)}"
            raise DemoScenarioError(msg)
        places = 6 if symbol == USDCAD else 4
        closes[symbol] = [_number(float(v), places) for v in history["Close"]]
        if symbol == USDCAD:
            continue
        if found := _window_events(ticker.dividends, 6):
            dividend_events[symbol] = found
        if found := _window_events(ticker.splits, 4, until=date.max):
            split_events[symbol] = found

    for symbol in derived:
        closes[symbol] = [
            _number(float(price) / float(rate), 4)
            for price, rate in zip(
                closes[USD_LINES[symbol]],
                closes[USDCAD],
                strict=True,
            )
        ]

    lines = [
        f"# Fetched from Yahoo Finance on {date.today().isoformat()}.",  # noqa: DTZ011
        f'FIRST_MONTH = "{FIRST_MONTH}"',
        *_render_mapping("CLOSES", closes),
        *_render_mapping("DIVIDENDS", dividend_events),
        *_render_mapping("SPLITS", split_events),
    ]
    _DATA.write_text(
        f"{_DOCSTRING}\n" + "\n".join(lines) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(  # noqa: T201
        f"Price history written: {len(closes)} series, splits {split_events}, "
        f"derived from their CAD line: {derived or 'none'}",
    )


def main() -> None:
    """Run the price history tool."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--refresh",
        action="store_true",
        help="Refetch the price history from Yahoo Finance",
    )
    if parser.parse_args().refresh:
        refresh_price_history()


if __name__ == "__main__":
    main()
